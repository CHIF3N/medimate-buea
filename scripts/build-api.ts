// Bundles server/*.ts into self-contained api/*.js functions for Vercel: `npm run build:api`
// (Bundling avoids Node ESM import-extension issues and keeps the USSD logic shared with the app.)
import { build } from 'esbuild';

await build({
  entryPoints: ['server/ussd.ts', 'server/pay.ts', 'server/fapshi-webhook.ts'],
  outdir: 'api',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  legalComments: 'none',
  banner: { js: '// Generated by scripts/build-api.ts from server/*.ts — do not edit.' },
});
console.log('api bundled');
